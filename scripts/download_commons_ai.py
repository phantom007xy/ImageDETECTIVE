"""Download AI-generated images from Wikimedia Commons, per generator: a free test set of generators we never trained on.

Why: our AI training images come from Muse Image, FLUX (SID-Set), SD 1.5/2.1, SD 3.5 and Kandinsky. Judges may upload
pictures from ChatGPT, Gemini, Midjourney, Grok and others. Commons has user-uploaded pictures of many of them, in
categories per generator ("Images generated by Midjourney", ...), mostly public domain (no human author).

Same licence rule as scripts/download_commons.py (CC0, public domain or CC BY without SA); JPEG, PNG or WebP; at least
0.25 MP; not extremely wide or tall. Files up to 2048 px are kept as they are, bigger ones as Commons' 2048-px copy.
Many are illustrations, not photos: the photo-like ones are picked afterwards (by eye, contact sheets).

Writes:
  - the images to --out-dir/<generator>/
  - data/attribution/commons_ai_v1.csv (in the repo): generator, author, licence and link of every file
  - features/lists/commons_ai_v1.csv (path, label 1, source commons_ai/<generator>)

Usage:  python scripts/download_commons_ai.py --out-dir D:/Datasets/CommonsAI/v1
"""

import argparse
import csv
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import httpx

from download_commons import API, USER_AGENT, download, licence_ok, plain

# generator (our source tag) -> its Commons category; subcategories are included (e.g. DALL-E 3 under DALL-E)
GENERATORS = {
    "dalle": "Images generated by DALL-E",
    "bing_dalle3": "Images generated by Image Creator by Microsoft Bing",
    "midjourney": "Images generated by Midjourney",
    "stable_diffusion": "Images generated by Stable Diffusion",
    "chatgpt": "Images generated by ChatGPT",
    "gpt_image": "GPT Image",
    "gemini": "Images generated by Gemini",
    "nano_banana": "Images generated by Nano Banana",
    "imagen": "Images generated by Imagen",
    "flux": "Images generated by Flux (text-to-image model)",
    "ideogram": "Images generated by Ideogram",
    "grok": "Images generated by Grok",
    "meta_ai": "Images generated by Meta AI",
    "firefly": "Images generated by Adobe Firefly AI",
    "qwen": "Images generated by Qwen",
    "hidream": "Images generated by HiDream",
    "seedream": "Images generated by Seedream",
    "reve": "Images generated by Reve Image",
    "recraft": "Images generated by Recraft",
    "mai_image": "Images generated by MAI-Image-1",
    "stylegan": "Images generated by thispersondoesnotexist.com",
}
MIMES = {"image/jpeg": "jpg", "image/png": "png", "image/webp": "webp"}
FIELDS = ["file", "generator", "category", "title", "page_url", "author", "licence", "licence_url"]


def subcategories(client, category, depth):
    """The category and its subcategories, `depth` levels down."""
    found, level = [category], [category]
    for _ in range(depth):
        nxt = []
        for cat in level:
            data = client.get(API, params={"action": "query", "format": "json", "list": "categorymembers",
                                           "cmtitle": f"Category:{cat}", "cmtype": "subcat", "cmlimit": 500}).json()
            nxt += [m["title"].removeprefix("Category:") for m in data.get("query", {}).get("categorymembers", [])]
        nxt = [c for c in nxt if c not in found]
        found += nxt
        level = nxt
    return found


def files(client, category, generator, seen, want):
    """Files of one category that pass the filters (at most want)."""
    params = {"action": "query", "format": "json", "generator": "categorymembers", "gcmtitle": f"Category:{category}",
              "gcmtype": "file", "gcmlimit": 50, "prop": "imageinfo", "iiprop": "url|size|mime|extmetadata",
              "iiurlwidth": 2048, "iiextmetadatafilter": "LicenseShortName|LicenseUrl|Artist"}
    found = []
    while len(found) < want:
        data = client.get(API, params=params).json()
        for page in sorted(data.get("query", {}).get("pages", {}).values(), key=lambda p: p["title"]):
            info = (page.get("imageinfo") or [{}])[0]
            meta = info.get("extmetadata", {})
            licence = plain(meta.get("LicenseShortName", {}).get("value", ""))
            w, h = info.get("width", 0), info.get("height", 0)
            if (page["title"] in seen or info.get("mime") not in MIMES or not licence_ok(licence) or w * h < 0.25e6
                    or max(w, h) > 2.5 * min(w, h) or not info.get("thumburl")):
                continue
            seen.add(page["title"])
            found.append({"title": page["title"], "page_url": info["descriptionurl"], "generator": generator,
                          "category": category, "author": plain(meta.get("Artist", {}).get("value", "")) or "unknown",
                          "licence": licence, "licence_url": plain(meta.get("LicenseUrl", {}).get("value", "")),
                          "thumb": info["thumburl"], "ext": MIMES[info["mime"]] if w <= 2048 and h <= 2048 else
                          info["thumburl"].rsplit(".", 1)[-1].lower().replace("jpeg", "jpg")})
            if len(found) == want:
                break
        if "continue" not in data:
            break
        params.update(data["continue"])
        time.sleep(0.2)  # be gentle with the API
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, required=True)
    parser.add_argument("--per-generator", type=int, default=300)
    parser.add_argument("--depth", type=int, default=2, help="subcategory levels to include")
    args = parser.parse_args()

    seen, items = set(), []
    with httpx.Client(headers={"User-Agent": USER_AGENT}, timeout=60, follow_redirects=True) as client:
        for generator, category in GENERATORS.items():
            got = []
            for cat in subcategories(client, category, args.depth):
                got += files(client, cat, generator, seen, args.per_generator - len(got))
                if len(got) >= args.per_generator:
                    break
            print(f"  {generator:<18} {len(got):>4} files", flush=True)
            items += got
        for n, item in enumerate(items):
            item["file"] = f"{item['generator']}/commons_ai_{n:05d}.{item['ext']}"
            (args.out_dir / item["generator"]).mkdir(parents=True, exist_ok=True)
        with ThreadPoolExecutor(2) as pool:  # two downloads at a time: polite to Wikimedia's servers
            ok = list(pool.map(lambda it: download(client, it, args.out_dir / it["file"]), items))
    items = [it for it, good in zip(items, ok) if good]

    attribution = Path("data/attribution/commons_ai_v1.csv")
    with open(attribution, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=FIELDS, extrasaction="ignore", lineterminator="\n")
        writer.writeheader()
        writer.writerows(items)
    with open("features/lists/commons_ai_v1.csv", "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["path", "label", "source"], lineterminator="\n")
        writer.writeheader()
        writer.writerows({"path": str(args.out_dir / it["file"]), "label": 1, "source": f"commons_ai/{it['generator']}"}
                         for it in items)
    print(f"{len(items)} files kept, {len(ok) - len(items)} downloads failed | attribution: {attribution}")


if __name__ == "__main__":
    main()
